-- 1. هوية المنشأة
-- ---------------------------------------------------------------------------
create table public.org_settings (
  id boolean primary key default true check (id),  -- صف واحد فقط
  legal_name text not null,
  brand text not null default 'AGMA',
  cr_number text not null,
  unified_number text,
  vat_number text,
  national_address text,
  city text not null default 'الرياض',
  website text,
  phone text,
  email text,
  representative_name text,
  representative_title text,
  updated_at timestamptz not null default now()
);

comment on table public.org_settings is
  'الهوية القانونية للمنشأة — الطرف الأول الافتراضي في كل عقد (docs/14 §1). الرقم الضريبي من الشهادة الضريبية حصراً، لا يُستنتج من السجل.';

alter table public.org_settings enable row level security;
grant select on public.org_settings to authenticated;
grant update on public.org_settings to authenticated;

create policy "org_settings: team reads" on public.org_settings
  for select to authenticated using (public.is_team());
create policy "org_settings: admin updates" on public.org_settings
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create trigger org_settings_set_updated_at
  before update on public.org_settings
  for each row execute function public.set_updated_at();
create trigger org_settings_audit
  after insert or update or delete on public.org_settings
  for each row execute function public.audit_trigger();

